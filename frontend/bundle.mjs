#!/usr/bin/env node
// Bundles the frontend into a single self-contained standalone.html so it
// can be opened directly via file:// without an HTTP server.
//
// Usage:  node frontend/bundle.mjs
//
// Reads index.html / styles.css / data.js / shifts.js / app.js / tour.js from this
// folder and writes frontend/standalone.html. The modular files remain the
// source of truth; re-run this script after editing them.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));

function read(name) {
  return readFileSync(join(here, name), 'utf8');
}

// Parse docs/RELEASE_NOTES.md into pickable entries (one per "### heading" under a "## date").
// The Release notes page reads window.RELEASE_NOTES_SOURCE and publishes a curated subset.
function parseReleaseNotes(md) {
  const entries = [];
  let date = null, cur = null, n = 0;
  const flush = () => {
    if (cur) { cur.body = cur.bodyLines.join('\n').trim(); delete cur.bodyLines; entries.push(cur); cur = null; }
  };
  for (const line of md.split('\n')) {
    const mDate = /^##\s+(\d{4}-\d{2}-\d{2})\s*$/.exec(line);
    const mHead = /^###\s+(.+?)\s*$/.exec(line);
    if (mDate) { flush(); date = mDate[1]; n = 0; continue; }
    if (/^-{3,}\s*$/.test(line)) continue;                 // skip "---" section rules
    if (mHead && date) { flush(); cur = { id: `${date}::${n++}`, date, heading: mHead[1], bodyLines: [] }; continue; }
    if (cur) cur.bodyLines.push(line);
  }
  flush();
  return entries;
}
function buildReleaseNotesJs() {
  let entries = [];
  try {
    entries = parseReleaseNotes(readFileSync(join(here, '..', 'docs', 'RELEASE_NOTES.md'), 'utf8'));
  } catch (e) { /* no changelog available → empty source (page stays blank) */ }
  return `// GENERATED by bundle.mjs from docs/RELEASE_NOTES.md — do not edit by hand.\n`
    + `window.RELEASE_NOTES_SOURCE = ${JSON.stringify(entries)};\n`;
}

const css = read('styles.css');
const config = read('config.js');
const data = read('data.js');
const shifts = read('shifts.js');
const owners = read('owners.js');
const releaseNotes = buildReleaseNotesJs();
writeFileSync(join(here, 'release-notes.js'), releaseNotes);   // regenerate the committed source
const app = read('app.js');
const tour = read('tour.js');
const indexHtml = read('index.html');
const faviconDataUri = 'data:image/svg+xml;base64,' + Buffer.from(read('favicon.svg')).toString('base64');
// Inline the TKMS marker icon so standalone.html works via file:// (the modular app loads it
// by path: icons/tkms.svg — that file is the single source; replace it to change the icon).
const tkmsIconDataUri = 'data:image/svg+xml;base64,' + Buffer.from(read(join('icons', 'tkms.svg'))).toString('base64');

const bodyMatch = indexHtml.match(/<body[^>]*>([\s\S]*?)<\/body>/);
if (!bodyMatch) {
  throw new Error('Could not find <body> in index.html');
}
const bodyContent = bodyMatch[1]
  .replace(/<script\s+src=["'][^"']+["'][^>]*><\/script>\s*/g, '')
  .trim();

const out = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Case Tracker — Prototype (standalone)</title>
<link rel="icon" type="image/svg+xml" href="${faviconDataUri}">
<style>
${css}
</style>
</head>
<body>
${bodyContent}
<script>
window.TKMS_ICON_SRC = '${tkmsIconDataUri}';

${config}

${data}

${shifts}

${owners}

${releaseNotes}

${app}

${tour}
</script>
</body>
</html>
`;

writeFileSync(join(here, 'standalone.html'), out);
console.log(`Wrote ${join(here, 'standalone.html')} (${(out.length / 1024).toFixed(1)} KB)`);
